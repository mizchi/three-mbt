import { execFileSync } from 'node:child_process';
import { types, imports, functions } from '../bindings/react-three-fiber.mjs';

export function generateReactThreeFiber(output) {
  const mbt = ['// Generated by scripts/generate-react-three-fiber.mjs. Do not edit.'];
  const js = ['// Generated from bindings/react-three-fiber.mjs. Do not edit.', imports];
  for (const type of types) mbt.push(`///|\n#external\npub type ${type}`);
  for (const { name, args, returns, expression, generics, private: isPrivate, doc } of functions) {
    const symbol = name.replaceAll('::', '_');
    // Split signatures only at top-level commas (callbacks and generic types contain commas).
    let depth = 0, start = 0;
    const parameters = [];
    const parts = [];
    for (let i = 0; i <= args.length; i++) {
      if ('(['.includes(args[i])) depth++;
      if (')]'.includes(args[i])) depth--;
      if (i === args.length || (args[i] === ',' && depth === 0)) {
        const arg = args.slice(start, i).trim();
        if (arg) { parameters.push(arg.split(':')[0].trim()); parts.push(arg); }
        start = i + 1;
      }
    }
    const module = '#module("@mizchi/three-mbt/react-three-fiber")';
    if (generics) {
      const erased = parts.map(arg => /\bT\b/.test(arg.slice(arg.indexOf(':'))) );
      const ffiArgs = parts.map((arg, i) => erased[i] ? `${parameters[i]} : Raw` : arg).join(', ').replace(/^self :/, 'receiver :');
      const eraseReturn = /\bT\b/.test(returns);
      const call = `ffi_${symbol}(${parameters.map((p, i) => erased[i] ? `raw(${p})` : p).join(', ')})`;
      mbt.push(`///|\n${module}\nextern "js" fn ffi_${symbol}(${ffiArgs}) -> ${eraseReturn ? 'Raw' : returns} = "${symbol}"`);
      mbt.push(`///|\n${doc ? `/// ${doc}\n` : ''}${isPrivate ? '' : 'pub '}fn[${generics}] ${name}(${args}) -> ${returns} { ${eraseReturn ? `cast(${call})` : call} }`);
    } else {
      mbt.push(`///|\n${doc ? `/// ${doc}\n` : ''}${module}\n${isPrivate ? '' : 'pub '}extern "js" fn ${name}(${args}) -> ${returns} = "${symbol}"`);
    }
    js.push(`export const ${symbol} = (${parameters.join(', ')}) => ${expression};`);
  }
  output(new URL('../src/react_three_fiber/bindings_generated.mbt', import.meta.url), execFileSync('moonfmt', ['-'], { input: mbt.join('\n\n') + '\n', encoding: 'utf8' }));
  output(new URL('../js/react-three-fiber.js', import.meta.url), js.join('\n') + '\n');
}
